import numpy as np

a = np.array([1, 2, 3])
b = np.array([4, 5, 6])

# Soma elemento-a-elemento
soma = a + b
print("Soma elemento-a-elemento:", soma)

# Subtração elemento-a-elemento
subtracao = a - b
print("Subtração elemento-a-elemento:", subtracao)

# Multiplicação elemento-a-elemento
multiplicacao = a * b
print("Multiplicação elemento-a-elemento:", multiplicacao)

# Divisão elemento-a-elemento
divisao = a / b
print("Divisão elemento-a-elemento:", divisao)