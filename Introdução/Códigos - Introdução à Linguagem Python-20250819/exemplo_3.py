# Definindo tipos de dados explicitamente
idade = int(25)
altura = float(1.75)
nome = str("João")
is_student = bool(True)

print("Idade (com tipo explícito):", idade)
print("Tipo de dado de 'idade':", type(idade))

print("Altura (com tipo explícito):", altura)
print("Tipo de dado de 'altura':", type(altura))

print("Nome (com tipo explícito):", nome)
print("Tipo de dado de 'nome':", type(nome))

print("Estudante (com tipo explícito):", is_student)
print("Tipo de dado de 'is_student':", type(is_student))